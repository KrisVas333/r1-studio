let warned = new Set();
export function t(key, vars) {
  const e = S[key];
  if (!e) { if (!warned.has(key)) { warned.add(key); console.warn("i18n: missing key", key); } return key; }
  let s = e[I] !== undefined ? e[I] : e[0];
  if (vars && typeof s === "string") for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  return s;
}
