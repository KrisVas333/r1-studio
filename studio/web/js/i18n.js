// Static HTML: data-i18n (text), data-i18n-html, data-i18n-title, data-i18n-ph (placeholder), data-i18n-aria.
export function applyDom(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((e) => { e.innerHTML = t(e.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-title]").forEach((e) => { e.title = t(e.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-ph]").forEach((e) => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach((e) => { e.setAttribute("aria-label", t(e.dataset.i18nAria)); });
}

// LT | EN switch. beforeSwitch() may return false to cancel (e.g. a program is running).
export function langSwitch(beforeSwitch) {
  const box = document.createElement("div"); box.className = "langsw"; box.setAttribute("role", "group"); box.setAttribute("aria-label", t("lang.title"));
  for (const l of ["lt", "en"]) {
    const b = document.createElement("button"); b.type = "button"; b.textContent = l.toUpperCase(); b.lang = l;
    b.className = l === LANG ? "on" : ""; b.setAttribute("aria-pressed", l === LANG);
    b.onclick = async () => { if (l === LANG) return; if (beforeSwitch && (await beforeSwitch()) === false) return; setLang(l); };
    box.appendChild(b);
  }
  return box;
}

